const DICTS = { en, ar };

/** Translate a key for a language, interpolating {placeholders}. */
export function translate(lang, key, vars) {
  const table = DICTS[lang] || DICTS.en;
  let text = table[key];
  if (text === undefined) text = DICTS.en[key];
  if (text === undefined) return key;
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, (m, name) =>
    vars[name] === undefined ? m : String(vars[name])
  );
}

export function isSupportedUiLang(code) {
  return Object.prototype.hasOwnProperty.call(DICTS, code);
}
